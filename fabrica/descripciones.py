def armar(d):
    L = [d["h"], ""] + re.split(r"(?<=\.) ", d["intro"]) + ["", "CARACTERISTICAS"] + [f"- {x}" for x in d["car"]]
    if d["med"]: L += ["", "MEDIDAS Y CAPACIDAD"] + [f"- {x}" for x in d["med"]]
    L += ["", "IDEAL PARA"] + [f"- {x}" for x in d["uso"]]
    return "\n".join(L)
